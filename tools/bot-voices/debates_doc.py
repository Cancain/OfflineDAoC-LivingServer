"""Write docs/bot-voices/DEBATES.md: every debate scene in corpus.json, readable for review.

  python tools/bot-voices/debates_doc.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / 'source/server/GameServer/bots/autonomous/data/chat/corpus.json'
OUT = ROOT / 'docs/bot-voices/DEBATES.md'
REALMS = [('*', 'Any realm'), ('mid', 'Midgard'), ('alb', 'Albion'), ('hib', 'Hibernia')]


def who(role, spec):
    parts = []
    if spec.get('class'):
        parts.append('/'.join(spec['class']))
    if spec.get('type'):
        parts.append('/'.join(spec['type']))
    return f"{role} ({', '.join(parts)})" if parts else role


def main():
    scenes = json.loads(CORPUS.read_text(encoding='utf-8'))['scenes']
    out = ['# Bot voices: debate scenes', '',
           f'{len(scenes)} scenes, {sum(len(s["beats"]) for s in scenes)} lines. Played in /faction by bots of one realm: '
           'A opens and the others take sides. `{q}` is an optional opener ("hey", "so"). New writing; the arguments '
           'are period knowledge (see RESEARCH-BRIEF.md). Generated by `tools/bot-voices/debates_doc.py`.', '']
    for realm, title in REALMS:
        group = [s for s in scenes if s['realm'] == realm]
        if not group:
            continue
        out += [f'## {title} ({len(group)})', '']
        for s in group:
            roles = ', '.join(who(r, spec) for r, spec in s['roles'].items())
            out += [f'### {s["id"].replace("_", " ")}', '',
                    f'Levels {s["levels"][0]}–{s["levels"][1]}' + (f' · roles: {roles}' if roles else ''), '']
            out += [f'- **{b["role"]}:** {b["text"]}' for b in s['beats']]
            out.append('')
    OUT.write_text('\n'.join(out), encoding='utf-8')
    print('wrote', OUT.relative_to(ROOT), len(scenes), 'scenes')


if __name__ == '__main__':
    main()
